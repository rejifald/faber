#!/bin/sh
# Build and ad-hoc sign faber-vm (ADR-0026). Virtualization refuses to create VMs without the
# com.apple.security.virtualization entitlement, so the signature is part of the build, and
# the build fails unless the signed binary carries exactly that entitlement and nothing else.
# Swift and Apple's frameworks only (ADR-0026, check 19): no packages, no Homebrew.
#
#   build.sh           the launcher:        $out/faber-vm
#   build.sh --agent   the guest agent:     $out/faber-agent (no entitlements at all)
#   build.sh --tests   the test executable: $out/faber-vm-tests (test.sh runs it)
#
# Shared/ is compiled into all three; agent/Sources into the agent and the tests.
#
# Everything goes to a scratch directory, never into the tree:
#   FABER_VM_OUT   output directory (default: $TMPDIR/faber-vm)
#   FABER_VERSION  the version to stamp (a release build sets it); otherwise it is derived
#                  exactly as build.rs derives faber's: <Cargo.toml [package] version>, plus
#                  +g<git rev-parse --short=7 HEAD> inside a git checkout.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/.." && pwd)
out=${FABER_VM_OUT:-${TMPDIR:-/tmp}/faber-vm}
entitlements=$here/faber-vm.entitlements

case "${1:-}" in
  "") target=launcher ;;
  --agent) target=agent ;;
  --tests) target=tests ;;
  *) echo "usage: build.sh [--agent|--tests]" >&2; exit 2 ;;
esac

mkdir -p "$out/gen"

# --- the version ---------------------------------------------------------------------------
if [ -n "${FABER_VERSION:-}" ]; then
  version=$FABER_VERSION
else
  pkg=$(awk '
    /^\[package\][[:space:]]*$/ { inpkg = 1; next }
    /^\[/                       { inpkg = 0 }
    inpkg && /^version[[:space:]]*=/ {
      sub(/^[^"]*"/, ""); sub(/".*$/, ""); print; exit
    }' "$root/Cargo.toml")
  [ -n "$pkg" ] || { echo "build.sh: no [package] version in $root/Cargo.toml" >&2; exit 1; }
  if sha=$(git -C "$root" rev-parse --short=7 HEAD 2>/dev/null) && [ -n "$sha" ]; then
    version=$pkg+g$sha
  else
    version=$pkg
  fi
fi
# A semver with optional build metadata, nothing a Swift string literal could misread. The
# whole string is matched, not line by line: a newline is refused like any other byte.
case "$version" in
  ""|*[!0-9A-Za-z.+-]*) echo "build.sh: refusing to stamp that version: only [0-9A-Za-z.+-] is allowed" >&2; exit 1 ;;
esac
printf '// Generated by launcher/build.sh. Not in the tree.\nlet faberVMVersion = "%s"\n' "$version" \
  > "$out/gen/Version.swift"

# --- compile -------------------------------------------------------------------------------
flags="-O -swift-version 6 -warnings-as-errors -target arm64-apple-macos15.0"
frameworks="-framework Foundation -framework Virtualization -framework vmnet"

agentFrameworks="-framework Foundation -framework SystemConfiguration"

case "$target" in
  launcher)
    bin=$out/faber-vm
    # shellcheck disable=SC2086
    swiftc $flags $frameworks -module-name faber_vm -o "$bin" \
      "$here"/Sources/*.swift "$here"/Shared/*.swift "$here/main/main.swift" "$out/gen/Version.swift"
    ;;
  agent)
    # The guest agent runs inside the guest: Foundation, SystemConfiguration and Darwin only,
    # never Virtualization or vmnet.
    bin=$out/faber-agent
    # shellcheck disable=SC2086
    swiftc $flags $agentFrameworks -module-name faber_agent -o "$bin" \
      "$here"/agent/Sources/*.swift "$here"/Shared/*.swift "$here/agent/main.swift" "$out/gen/Version.swift"
    ;;
  tests)
    bin=$out/faber-vm-tests
    # shellcheck disable=SC2086
    swiftc $flags $frameworks -framework SystemConfiguration -module-name faber_vm_tests -o "$bin" \
      "$here"/Sources/*.swift "$here"/Shared/*.swift "$here"/agent/Sources/*.swift "$here"/Tests/*.swift \
      "$out/gen/Version.swift"
    ;;
esac

# --- sign, then prove the signature carries exactly the entitlements it should ---------------
# Hardened runtime: no unsigned code, no DYLD_* injection, no debugger attach. The launcher and
# its tests carry com.apple.security.virtualization alone; the agent carries none.
if [ "$target" = agent ]; then
  codesign --force -s - --options runtime "$bin"
else
  codesign --force -s - --options runtime --entitlements "$entitlements" "$bin"
fi
if ! codesign -d --verbose=2 "$bin" 2>&1 | /usr/bin/grep -Eq "^CodeDirectory .*flags=0x[0-9a-f]*\(.*runtime.*\)"; then
  echo "build.sh: $bin is not signed with the hardened runtime" >&2
  exit 1
fi
signed=$out/gen/$(basename "$bin").entitlements.plist
codesign -d --entitlements - --xml "$bin" > "$signed" 2>/dev/null
if [ "$target" = agent ]; then
  # codesign prints nothing for a binary with no entitlements; anything it prints is one too many.
  if [ -s "$signed" ] && [ "$(plutil -convert json -o - "$signed" 2>/dev/null || echo unreadable)" != "{}" ]; then
    echo "build.sh: $bin carries entitlements; the guest agent must carry none:" >&2
    plutil -p "$signed" >&2 || cat "$signed" >&2
    exit 1
  fi
  echo "signed entitlements of $bin: none"
else
  echo "signed entitlements of $bin:"
  plutil -p "$signed"
  got=$(plutil -convert json -o - "$signed")
  want='{"com.apple.security.virtualization":true}'
  if [ "$got" != "$want" ]; then
    echo "build.sh: $bin carries entitlements $got; expected exactly $want" >&2
    exit 1
  fi
fi

echo "version $version"
echo "built $bin"
