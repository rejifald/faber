//! Stamps the running binary with the commit it was built from.
//!
//! A fleet that auto-updates needs every host to be able to answer "which faber
//! is this, exactly?" — and a semver alone can't, because the builder Mac
//! routinely runs a work-in-progress build carrying an unbumped version number.
//! `FABER_VERSION` is `0.2.0` when there is no git checkout to ask (a release
//! tarball, a vendored build) and `0.2.0+g1a2b3c4` when there is.
//!
//! Everything after `+` is build metadata: [`faber::update::parse_version`]
//! ignores it, so a stamped binary still compares equal to the release it came
//! from.
//!
//! A release build gets its semver from `.github/workflows/release.yml`, which
//! stamps it into `Cargo.toml` and checks that the binary reports exactly
//! `<version>+g<prefix of the built commit>` (ADR-0031). Local builds report the
//! committed `Cargo.toml` version, which releases no longer bump.
//!
//! It also embeds the React dashboard (ADR-0042 § 7): every file under
//! `ui/dist/dashboard`, when `npm run build` in `ui/` has made it, as
//! `$OUT_DIR/ui_dashboard.rs`, which `src/ui_bundle.rs` includes. Without the
//! bundle the table is empty and the daemon has a plain "UI not built" page, so
//! a bare `cargo build` and the Linux test leg need no Node. A release sets
//! `FABER_REQUIRE_UI=1`, and then a missing bundle fails the build.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    // In a git worktree `.git` is a file rather than a directory, so this path
    // may not exist; cargo simply doesn't track it then, which costs a stale SHA
    // only until the next real source change triggers a rebuild anyway.
    println!("cargo:rerun-if-changed=.git/HEAD");

    let pkg = std::env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".to_string());
    let sha = std::process::Command::new("git")
        .args(["rev-parse", "--short=7", "HEAD"])
        .output()
        .ok()
        .filter(|out| out.status.success())
        .map(|out| String::from_utf8_lossy(&out.stdout).trim().to_string())
        .filter(|sha| !sha.is_empty());

    let version = match sha {
        Some(sha) => format!("{pkg}+g{sha}"),
        None => pkg,
    };
    println!("cargo:rustc-env=FABER_VERSION={version}");

    // The target triple this binary was built for, so the updater can ask a
    // release for *its own* platform's asset rather than a hardcoded one. Cargo
    // exposes TARGET to build scripts only, which is why it is stamped here
    // rather than derived from `cfg!` at use site: a triple assembled from
    // target_os/target_arch guesses at the vendor and libc fields, and would
    // drift from what `.github/workflows/release.yml` actually names the asset.
    let target = std::env::var("TARGET").unwrap_or_else(|_| "unknown".to_string());
    println!("cargo:rustc-env=FABER_TARGET={target}");

    embed_dashboard();
}

/// Where `npm run build` in `ui/` writes the dashboard entry.
const DASHBOARD: &str = "ui/dist/dashboard";

fn embed_dashboard() {
    // `ui/dist` is always there (its `.gitkeep` is tracked), so watching it
    // costs nothing until a build changes it. Cargo scans a watched directory
    // recursively; a watched path that is missing would rerun this every build.
    println!("cargo:rerun-if-changed=ui/dist");
    println!("cargo:rerun-if-env-changed=FABER_REQUIRE_UI");

    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let root = manifest.join(DASHBOARD);
    let mut files = Vec::new();
    if root.join("index.html").is_file() {
        collect(&root, &root, &mut files);
    } else if std::env::var_os("FABER_REQUIRE_UI").is_some_and(|v| !v.is_empty() && v != "0") {
        panic!(
            "FABER_REQUIRE_UI is set but {DASHBOARD}/index.html is missing: \
             run `npm ci && npm run build` in ui/ first (ADR-0042 § 7)"
        );
    }
    files.sort();

    let mut table = String::from(
        "// Generated by build.rs from ui/dist/dashboard (ADR-0042 § 7). Do not edit.\n\
         pub static FILES: &[(&str, &[u8])] = &[\n",
    );
    for (rel, abs) in &files {
        writeln!(
            table,
            "    ({rel:?}, include_bytes!({:?})),",
            abs.display().to_string()
        )
        .expect("writing to a String");
    }
    table.push_str("];\n");
    let out =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets it")).join("ui_dashboard.rs");
    std::fs::write(&out, table).expect("write ui_dashboard.rs");
}

/// Every file under `dir`, as (path relative to `root` with `/` separators,
/// absolute path).
fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = std::fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for entry in entries {
        let path = entry.expect("directory entry").path();
        if path.is_dir() {
            collect(root, &path, files);
        } else {
            let rel = path.strip_prefix(root).expect("under root");
            let rel = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            files.push((rel, path));
        }
    }
}
